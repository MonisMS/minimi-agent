import type { DatabaseSync } from 'node:sqlite';
import {
  eventEnvelopeSchema,
  type EventEnvelope,
} from '../../shared/events.js';
import { ACTIVE_RUN_STATES } from '../../shared/domain.js';
import type { Clock } from '../clock.js';
import type { Scope } from '../db/conversations.js';
import { getRun } from '../db/runs.js';
import { runTransaction } from '../db/transaction.js';
import { RunNotFoundError, RunStateConflictError } from './errors.js';

export type PersistedEventType = Exclude<EventEnvelope['type'], 'snapshot'>;
export type EventListener = (event: EventEnvelope) => void;

const TERMINAL_EVENT_TYPES: ReadonlySet<PersistedEventType> = new Set([
  'result_ready',
  'done',
  'error',
]);

const DELTA_FLUSH_MS = 50;

interface EventRow {
  run_id: string;
  conversation_id: string;
  seq: number;
  type: string;
  payload_json: string;
  created_at: string;
}

interface DeltaBuffer {
  scope: Scope;
  text: string;
}

function parseRow(row: EventRow): EventEnvelope {
  return eventEnvelopeSchema.parse({
    version: 1,
    runId: row.run_id,
    conversationId: row.conversation_id,
    seq: row.seq,
    timestamp: row.created_at,
    type: row.type,
    payload: JSON.parse(row.payload_json) as unknown,
  });
}

export class RunEventBus {
  private readonly listeners = new Map<string, Set<EventListener>>();

  subscribe(runId: string, listener: EventListener): () => void {
    let listeners = this.listeners.get(runId);
    if (!listeners) {
      listeners = new Set();
      this.listeners.set(runId, listeners);
    }
    listeners.add(listener);
    return () => {
      const current = this.listeners.get(runId);
      if (!current) return;
      current.delete(listener);
      if (current.size === 0) this.listeners.delete(runId);
    };
  }

  publish(event: EventEnvelope): void {
    const listeners = this.listeners.get(event.runId);
    if (!listeners) return;
    for (const listener of [...listeners]) {
      listener(event);
    }
  }
}

export interface RunEventWriterOptions {
  database: DatabaseSync;
  clock: Clock;
  bus?: RunEventBus;
  deltaFlushMs?: number;
}

export class RunEventWriter {
  readonly bus: RunEventBus;
  private readonly database: DatabaseSync;
  private readonly clock: Clock;
  private readonly deltaFlushMs: number;
  private readonly buffers = new Map<string, DeltaBuffer>();
  private readonly timers = new Map<string, ReturnType<typeof setTimeout>>();

  constructor(options: RunEventWriterOptions) {
    this.database = options.database;
    this.clock = options.clock;
    this.bus = options.bus ?? new RunEventBus();
    this.deltaFlushMs = options.deltaFlushMs ?? DELTA_FLUSH_MS;
  }

  append(
    scope: Scope,
    runId: string,
    type: PersistedEventType,
    payload: unknown,
  ): EventEnvelope {
    if ((type as string) === 'snapshot') {
      throw new Error('Snapshot events are generated by the stream, not persisted');
    }
    const run = getRun(this.database, scope, runId);
    if (!run) throw new RunNotFoundError();

    const now = this.clock.now().toISOString();
    const terminalAllowed = TERMINAL_EVENT_TYPES.has(type) ? 1 : 0;
    const activePlaceholders = ACTIVE_RUN_STATES.map(() => '?').join(', ');
    const deltaText =
      type === 'answer_delta' &&
      payload !== null &&
      typeof payload === 'object' &&
      typeof (payload as { text?: unknown }).text === 'string'
        ? (payload as { text: string }).text
        : null;
    if (type === 'answer_delta' && (deltaText === null || deltaText.length === 0)) {
      throw new Error('Answer deltas require non-empty text');
    }

    const envelope = runTransaction(this.database, () => {
      const assignments = ['event_seq = event_seq + 1', 'updated_at = ?'];
      const values: Array<string | number> = [now];
      if (deltaText !== null) {
        assignments.push("answer_text = COALESCE(answer_text, '') || ?");
        values.push(deltaText);
      }

      const updated = this.database
        .prepare(
          `UPDATE runs
           SET ${assignments.join(', ')}
           WHERE id = ? AND owner_id = ? AND namespace = ?
             AND (state IN (${activePlaceholders}) OR ? = 1)
             AND EXISTS (
               SELECT 1 FROM conversations c
               WHERE c.id = runs.conversation_id
                 AND c.deleted_at IS NULL
                 AND c.generation = runs.captured_generation
             )
           RETURNING event_seq`,
        )
        .get(
          ...values,
          runId,
          scope.ownerId,
          scope.namespace,
          ...ACTIVE_RUN_STATES,
          terminalAllowed,
        ) as { event_seq: number } | undefined;

      if (!updated) {
        const actual = getRun(this.database, scope, runId);
        if (!actual) throw new RunNotFoundError();
        throw new RunStateConflictError('The run is no longer active');
      }

      const parsed = eventEnvelopeSchema.parse({
        version: 1,
        runId,
        conversationId: run.conversationId,
        seq: updated.event_seq,
        timestamp: now,
        type,
        payload,
      });

      this.database
        .prepare(
          `INSERT INTO run_events
            (run_id, conversation_id, seq, type, payload_json, created_at)
           VALUES (?, ?, ?, ?, ?, ?)`,
        )
        .run(
          parsed.runId,
          parsed.conversationId,
          parsed.seq,
          parsed.type,
          JSON.stringify(parsed.payload),
          parsed.timestamp,
        );

      return parsed;
    });

    this.bus.publish(envelope);
    return envelope;
  }

  appendDelta(scope: Scope, runId: string, text: string): void {
    if (text.length === 0) return;
    const existing = this.buffers.get(runId);
    if (existing) {
      existing.text += text;
    } else {
      this.buffers.set(runId, { scope, text });
    }
    if (this.timers.has(runId)) return;

    const timer = setTimeout(() => {
      this.timers.delete(runId);
      try {
        this.flushDelta(scope, runId);
      } catch {
        this.buffers.delete(runId);
      }
    }, this.deltaFlushMs);
    timer.unref?.();
    this.timers.set(runId, timer);
  }

  flushDelta(scope: Scope, runId: string): EventEnvelope | null {
    const timer = this.timers.get(runId);
    if (timer) {
      clearTimeout(timer);
      this.timers.delete(runId);
    }
    const buffer = this.buffers.get(runId);
    if (!buffer) return null;
    this.buffers.delete(runId);
    return this.append(buffer.scope ?? scope, runId, 'answer_delta', {
      text: buffer.text,
    });
  }

  flushAll(): void {
    for (const runId of [...this.buffers.keys()]) {
      const buffer = this.buffers.get(runId);
      if (!buffer) continue;
      try {
        this.flushDelta(buffer.scope, runId);
      } catch {
        this.buffers.delete(runId);
      }
    }
  }

  close(): void {
    for (const timer of this.timers.values()) clearTimeout(timer);
    this.timers.clear();
    this.flushAll();
    this.buffers.clear();
  }

  listAfter(scope: Scope, runId: string, afterSeq: number): EventEnvelope[] {
    const run = getRun(this.database, scope, runId);
    if (!run) return [];
    const rows = this.database
      .prepare(
        `SELECT run_id, conversation_id, seq, type, payload_json, created_at
         FROM run_events
         WHERE run_id = ? AND seq > ?
         ORDER BY seq ASC`,
      )
      .all(runId, afterSeq) as unknown as EventRow[];
    return rows.map(parseRow);
  }

  getTerminalEvent(scope: Scope, runId: string): EventEnvelope | null {
    const run = getRun(this.database, scope, runId);
    if (!run) return null;
    const row = this.database
      .prepare(
        `SELECT run_id, conversation_id, seq, type, payload_json, created_at
         FROM run_events
         WHERE run_id = ? AND type IN ('done', 'error')
         ORDER BY seq DESC
         LIMIT 1`,
      )
      .get(runId) as EventRow | undefined;
    return row ? parseRow(row) : null;
  }
}
